import pandas as pd
df = pd.read_csv("credit_default_classification.csv")

expected_id = "CR3" + df.index.to_series().map(lambda i: f"{i:04d}")
mask = df["customer"].isna() & (df.index < 250)
df.loc[mask, "customer"] = expected_id[mask]

num_cols = ["age", "loan_amount_k", "credit_score", "num_open_accounts",
            "income_k", "months_since_delinq"]
for col in num_cols:
    df[col] = df[col].fillna(df[col].median())

df["credit_score_dup"] = df["credit_score"]

df["home_owner"] = df["home_owner"].fillna("No")
df["loan_purpose"] = df["loan_purpose"].fillna("Business")

df["defaulted"] = df["defaulted"].fillna(df["defaulted"].mode()[0])

int_cols = ["age", "num_open_accounts", "credit_score",
            "months_since_delinq", "credit_score_dup", "defaulted"]
df[int_cols] = df[int_cols].round().astype(int)
df["customer"] = df["customer"].fillna(expected_id)
print(df["customer"].isna().sum())
df.to_csv("credit_default_classification_filled.csv", index=False)

df.info()

for col in ["home_owner", "loan_purpose", "customer"]:
    df[col] = df[col].astype("string").str.strip()

yes_variants = {"yes", "ye", "es", "ys", "y"}
no_variants = {"no", "n", "o"}
def clean_home_owner(v):
    v = v.lower()
    if v in yes_variants:
        return "Yes"
    if v in no_variants:
        return "No"
    return pd.NA
df["home_owner"] = df["home_owner"].map(clean_home_owner)

import difflib
valid_purposes = ["Business", "Home improvement", "Debt consolidation", "Car", "Education"]
lookup = {p.lower(): p for p in valid_purposes}
def clean_purpose(v):
    v = v.lower()
    if v in lookup:
        return lookup[v]
    match = difflib.get_close_matches(v, list(lookup), n=1, cutoff=0.6)
    return lookup[match[0]] if match else pd.NA
df["loan_purpose"] = df["loan_purpose"].map(clean_purpose)

df.loc[df["income_k"] < 0, "income_k"] = pd.NA
df["income_k"] = df["income_k"].astype(float)
df["income_k"] = df["income_k"].fillna(df["income_k"].median())

for col in ["home_owner", "loan_purpose"]:
    df[col] = df[col].fillna(df[col].mode()[0])

df = df.drop_duplicates()
df = df.drop_duplicates(subset="customer", keep="first").reset_index(drop=True)

assert df.isna().sum().sum() == 0
assert df["home_owner"].isin(["Yes", "No"]).all()
assert df["loan_purpose"].isin(valid_purposes).all()
assert (df["income_k"] >= 0).all()
df.to_csv("credit_default_classification_clean.csv", index=False)

